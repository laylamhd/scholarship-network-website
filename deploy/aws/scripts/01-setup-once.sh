#!/usr/bin/env bash
# =============================================================================
# 01-setup-once.sh — run ONCE (the files it creates live in the CloudShell home
# directory, which survives sandbox sessions).
#
#   ./scripts/01-setup-once.sh [path/to/schema.sql] [path/to/data.sql]
#
#  1. creates ~/tbhf/secrets.env with random passwords (never overwritten)
#  2. moves your Supabase export into ~/tbhf/import/ (private, never in git)
#  3. downloads the images/files the export links to on Supabase Storage
#     into ~/tbhf/media/ so they can be served from Amazon S3
# =============================================================================
. "$(dirname "$0")/lib.sh"
SCHEMA_SRC="${1:-$HOME/schema.sql}"
DATA_SRC="${2:-$HOME/data.sql}"
umask 077
mkdir -p "$TBHF_HOME"/{import,artifacts,backups,media}
chmod 700 "$TBHF_HOME"

step "1. Secrets ($SECRETS)"
if [ -f "$SECRETS" ]; then
  ok "already exists — keeping it (delete it only if you want new passwords AND a fresh database import)"
else
  python3 - > "$SECRETS" <<'PY'
import secrets, string
alnum = string.ascii_letters + string.digits
pw = lambda n: "".join(secrets.choice(alnum) for _ in range(n))
print("# Generated by 01-setup-once.sh — keep private. Letters and digits only (RDS rule).")
print(f'DB_MASTER_PASSWORD="{pw(28)}"   # RDS master user tbhf_admin (used only by the ops instance)')
print(f'APP_DB_PASSWORD="{pw(28)}"      # database login of the website (role tbhf_app)')
print(f'SESSION_SECRET="{secrets.token_urlsafe(48)}"  # signs the login cookie')
print(f'SEED_PASSWORD="Tbhf-{pw(10)}"     # first password of every imported account')
print(f'ADMIN_CODE="{pw(20)}"   # new admin access code, 20 characters (the exported one is retired)')
PY
  chmod 600 "$SECRETS"
  ok "created"
fi

step "2. Supabase export"
for pair in "schema.sql:$SCHEMA_SRC" "data.sql:$DATA_SRC"; do
  name="${pair%%:*}"; src="${pair#*:}"; dst="$TBHF_HOME/import/$name"
  if [ -f "$src" ] && [ "$src" != "$dst" ]; then
    mv -f "$src" "$dst" && chmod 600 "$dst"; ok "$name → $dst"
  elif [ -f "$dst" ]; then
    ok "$name already in place"
  else
    die "$src not found — upload it with CloudShell Actions → Upload file, then run again"
  fi
done
grep -q 'CREATE TABLE public.profiles' "$TBHF_HOME/import/schema.sql" || die "schema.sql does not look like the Supabase export"
grep -q 'COPY public.profiles' "$TBHF_HOME/import/data.sql" || die "data.sql does not look like the Supabase export"

step "3. Copy the files stored on Supabase Storage"
python3 - "$TBHF_HOME/import/data.sql" "$TBHF_HOME/media" <<'PY'
import os, re, sys, urllib.parse, urllib.request
data, out = sys.argv[1], sys.argv[2]
pat = re.compile(r"https://[a-z0-9]+\.supabase\.co/storage/v1/object/public/([a-z0-9-]+)/([^\s'\"\\),]+)")
urls = sorted({m.group(0) for m in pat.finditer(open(data, encoding="utf-8").read())})
got = skipped = failed = 0
for url in urls:
    m = pat.match(url)
    bucket, path = m.group(1), urllib.parse.unquote(m.group(2))
    dest = os.path.join(out, bucket, path)
    if os.path.exists(dest):
        skipped += 1; continue
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    try:
        with urllib.request.urlopen(url, timeout=30) as r, open(dest, "wb") as f:
            f.write(r.read())
        got += 1
    except Exception as e:
        failed += 1
        print(f"  ! could not download {bucket}/{path}: {e}")
print(f"  {len(urls)} linked files: {got} downloaded, {skipped} already here, {failed} failed")
PY
ok "files in $TBHF_HOME/media (uploaded to the media bucket by deploy.sh)"

echo
ok "setup complete — next: ./scripts/00-check-sandbox.sh then ./scripts/deploy.sh"
